PLANTS = ['M01', 'M02', 'M03', 'M04', 'M05', 'M06', 'M07']
PLANT_SIZE = {'M01': 1.25, 'M02': 1.10, 'M03': 1.05, 'M04': 0.95, 'M05': 0.90, 'M06': 0.90, 'M07': 0.85}
SEASON = [1.06, 1.08, 0.82, 1.04, 1.02, 0.93, 0.86, 0.88, 1.02, 1.07, 1.10, 1.11]  # month 3 holds Ramadan
PEAK = {10, 11, 12, 2}
DIESEL_SAR_PER_L = 1.66
WRITE_OFF_SAR_PER_LOAD = 1600
OVERTIME_SAR_PER_HOUR = 62
LITRES_PER_EMPTY_KM = 0.45


def dispatch_records(rng):
    rows = []
    for m in range(1, 13):
        for p in PLANTS:
            base = 2185 * PLANT_SIZE[p] * SEASON[m - 1]
            loads = int(round(base * rng.uniform(0.96, 1.04)))
            m3 = int(round(loads * rng.uniform(8.1, 8.3)))
            ret = int(round(loads * rng.uniform(0.019, 0.027)))
            late = int(round(ret * rng.uniform(0.52, 0.64)))
            quality = int(round(ret * rng.uniform(0.18, 0.26)))
            cancel = ret - late - quality
            loaded_km = int(round(loads * rng.uniform(21.5, 24.5)))
            empty_km = int(round(loaded_km * rng.uniform(0.92, 1.02)))
            litres = int(round(loaded_km * 0.62 + empty_km * LITRES_PER_EMPTY_KM))
            overtime = int(round(loads * rng.uniform(0.40, 0.52) * (1.25 if m in PEAK else 1.0)))
            lost = int(round(loads * rng.uniform(0.020, 0.034))) if m in PEAK else int(round(loads * rng.uniform(0.0, 0.004)))
            wait = round(rng.uniform(36, 47), 1)
            rows.append([f'2025-{m:02d}', p, loads, m3, ret, late, quality, cancel, loaded_km, empty_km,
                         litres, overtime, lost, wait])
    return rows


