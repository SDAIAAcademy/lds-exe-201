def write_recorded_runs():
    """Recorded stand-in runs (scripted outputs, not a model) for labs/prototype/run_cases.py."""
    import json
    out = HERE.parent / 'prototype' / 'recorded'
    out.mkdir(parents=True, exist_ok=True)
    a = []
    for c in PROTO_A_CASES:
        h, s, p, stop = PROTO_A_RUN.get(c[0], (c[2], c[3], c[4], c[5]))
        a.append({'case_id': c[0], 'output': {'hazard': h, 'severity': s, 'plant': p, 'stop': stop}})
    b = [{'case_id': k, 'output': v[0]} for k, v in PROTO_B_RUN.items()]
    note = 'Scripted stand-in outputs written by labs/_tools/prepare_files.py; not produced by a model.'
    (out / 'run_a.json').write_text(json.dumps({'note': note, 'runs': a}, ensure_ascii=False, indent=1) + '\n', encoding='utf-8', newline='\n')
    (out / 'run_b.json').write_text(json.dumps({'note': note, 'runs': b}, ensure_ascii=False, indent=1) + '\n', encoding='utf-8', newline='\n')


if __name__ == '__main__':
    write_recorded_runs()
